-- 1. Соответствие команд провайдера нашим. Основной ключ — provider_team_id,
-- имя используется только как резерв.
create table if not exists public.team_aliases (
  alias text primary key,
  team_name text not null,
  provider text not null default 'api-football',
  provider_team_id bigint,
  created_at timestamptz not null default now()
);

create unique index if not exists team_aliases_provider_id_idx
  on public.team_aliases (provider, provider_team_id);

alter table public.team_aliases enable row level security;
drop policy if exists "team_aliases_read_all" on public.team_aliases;
create policy "team_aliases_read_all" on public.team_aliases
  for select using (true);
grant select on public.team_aliases to anon, authenticated;
grant all on public.team_aliases to service_role;

