-- 2. Матчи провайдера: расписание, live-счёт, итог
create table if not exists public.fixtures (
  id bigint generated by default as identity primary key,
  provider text not null default 'api-football',
  external_id text not null,
  league_code text not null,
  season int not null,
  round int,
  kickoff_at timestamptz,
  status text not null default 'scheduled',
  minute int,
  home text not null,
  away text not null,
  gh int,
  ga int,
  updated_at timestamptz not null default now(),
  unique (provider, external_id)
);

create index if not exists fixtures_round_idx
  on public.fixtures (league_code, round, kickoff_at);

alter table public.fixtures enable row level security;
drop policy if exists "fixtures_read_all" on public.fixtures;
create policy "fixtures_read_all" on public.fixtures
  for select using (true);
grant select on public.fixtures to anon, authenticated;
grant all on public.fixtures to service_role;

-- 3. Журнал запусков
create table if not exists public.sync_log (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  source text not null default 'cron',
  ok boolean,
  requests_used int not null default 0,
  fixtures_seen int not null default 0,
  fixtures_updated int not null default 0,
  finished_added int not null default 0,
  unmatched int not null default 0,
  message text
);

alter table public.sync_log enable row level security;
drop policy if exists "sync_log_read_admin" on public.sync_log;
create policy "sync_log_read_admin" on public.sync_log
  for select to authenticated
  using (exists (select 1 from public.admins a where a.email = (auth.jwt() ->> 'email')));
grant select on public.sync_log to authenticated;
grant all on public.sync_log to service_role;

-- 4. Счётчик бесплатного лимита (100 запросов в сутки)
create table if not exists public.sync_state (
  id int primary key default 1,
  day date not null default current_date,
  requests_used int not null default 0,
  quota_limit int not null default 100,
  last_run timestamptz,
  last_error text
);

insert into public.sync_state (id) values (1) on conflict (id) do nothing;

alter table public.sync_state enable row level security;
grant all on public.sync_state to service_role;

-- 5. Проверка
select 'fixtures' as table_name, count(*) from public.fixtures
union all
select 'team_aliases', count(*) from public.team_aliases
union all
select 'sync_log', count(*) from public.sync_log;
