-- Схема общей базы матчей для Supabase.
-- Выполните этот файл в SQL Editor проекта Supabase.
-- Перед запуском замените you@example.com на email, которым будете входить в админку.

-- 1. Матчи
create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  home text not null,
  away text not null,
  gh int not null check (gh between 0 and 20),
  ga int not null check (ga between 0 and 20),
  round int not null default 1 check (round >= 1),
  created_at timestamptz not null default now(),
  unique (home, away, round)
);

alter table public.matches enable row level security;

-- Читать матчи может любой посетитель
drop policy if exists "matches_read_all" on public.matches;
create policy "matches_read_all" on public.matches
  for select using (true);

-- 2. Список администраторов (менять может только service_role из панели Supabase)
create table if not exists public.admins (
  email text primary key
);

alter table public.admins enable row level security;

-- Вошедший пользователь может проверить только свою строку (нужно сайту,
-- чтобы показать пункт «Админка» лишь администраторам).
drop policy if exists "admins_read_self" on public.admins;
create policy "admins_read_self" on public.admins
  for select
  to authenticated
  using (email = (auth.jwt() ->> 'email'));

-- 3. Запись/удаление матчей — только админам из списка
drop policy if exists "matches_write_admin" on public.matches;
create policy "matches_write_admin" on public.matches
  for all
  to authenticated
  using (exists (select 1 from public.admins a where a.email = (auth.jwt() ->> 'email')))
  with check (exists (select 1 from public.admins a where a.email = (auth.jwt() ->> 'email')));

-- 4. Права для ролей API (без них PostgREST отвечает 401)
grant usage on schema public to anon, authenticated;
grant select on public.matches to anon, authenticated;
grant insert, update, delete on public.matches to authenticated;
grant select on public.admins to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- 5. Добавьте себя админом
insert into public.admins(email) values ('you@example.com')
on conflict (email) do nothing;
