-- Личные данные пользователя: история матчей и прогнозы.
-- Выполните этот файл в SQL Editor проекта Supabase ПОСЛЕ schema.sql.
-- Привязка к аккаунту: каждая строка принадлежит auth.uid().
-- Читать и менять свои строки может только вошедший пользователь.
-- ============================================================

-- 1. Личная история матчей пользователя
create table if not exists public.user_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  home text not null,
  away text not null,
  gh int not null check (gh between 0 and 20),
  ga int not null check (ga between 0 and 20),
  round int not null default 1 check (round >= 1),
  ts timestamptz not null default now()
);

-- Одна пара команд + тур у одного пользователя — единственный
alter table public.user_history
  add constraint user_history_unique unique (user_id, home, away, round);

alter table public.user_history enable row level security;

-- Пользователь работает только со своими строками
drop policy if exists "user_history_own" on public.user_history;
create policy "user_history_own" on public.user_history
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- 2. Личные прогнозы пользователя
create table if not exists public.user_predictions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  home text not null,
  away text not null,
  probs jsonb not null,   -- массив [pw, pd, pl]  
  lh numeric,
  la numeric,
  ts timestamptz not null default now()
);

-- У одного пользователя на пару команд — один прогноз (последний перезаписывает)
alter table public.user_predictions
  add constraint user_predictions_unique unique (user_id, home, away);

alter table public.user_predictions enable row level security;

drop policy if exists "user_predictions_own" on public.user_predictions;
create policy "user_predictions_own" on public.user_predictions
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- 3. Права для ролей API (PostgREST)
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.user_history to authenticated;
grant select, insert, update, delete on public.user_predictions to authenticated;
grant usage, select on all sequences in schema public to authenticated;